def stamp_footer():
    """Rewrite ONLY the build timestamp ('Last updated:') in live-site/index.html
    with the current UTC time. This is the deploy/build moment -- generated by the
    process, never handwritten.

    The verified/review date (the <span class="vdate"> field) is DELIBERATELY NOT
    touched here. A date carrying 'verified' / 'review' (复核日) wording may only be
    written when we have actually opened the official provider pages; it is a
    hand-maintained field and is NEVER auto-filled from the build time. The build
    timestamp and the verified date are two SEPARATE fields and must never share a
    value or be derived from the same source.
    """
    p = os.path.join(SITE_DIR, "index.html")
    with open(p, "rb") as f:
        data = f.read()
    now_dt = datetime.now(timezone.utc)
    now_ts = now_dt.strftime("%Y-%m-%dT%H:%M:%SZ").encode("ascii")
    # footer timestamp: group(1) keeps 'class="generated">Last updated: ' (with its
    # space); the old timestamp is matched by [^<]* and DROPPED; group(2) is </div>.
    new_data, n1 = re.subn(
        rb'(class="generated">Last updated: )[^<]*(</div>)',
        lambda m: m.group(1) + now_ts + m.group(2),
        data,
    )
    if n1 == 0:
        print("WARN: footer stamp pattern not found; leaving timestamp unchanged", file=sys.stderr)
        return
    print(f"  footer stamped -> Last updated: {now_ts.decode()}")
    with open(p, "wb") as f:
        f.write(new_data)


# --- Post-deploy verification -------------------------------------------------
# A "Verify:" line that only PRINTS a URL proves nothing: on 2026-10-30 two
# consecutive runs printed https://serverbudget.com/a2-hosting-coupon-not-working.html
# as "verified" while that page did not exist in live-site/ and returned 404.
# So the check below actually requests the URL and reports the real status code,
# and a non-200 makes the run fail instead of silently printing a dead link.
VERIFY_ORIGIN = "https://serverbudget.com"
VERIFY_PATH = "/vps-price"
# VERIFY_URL may be overridden to re-check some other path (used to prove the
# check actually fails on a dead link, e.g. the old /a2-hosting-coupon-not-working.html).
VERIFY_URL = os.environ.get("VERIFY_URL") or (VERIFY_ORIGIN + VERIFY_PATH)


def verify_live(attempts=5, delay=3):
    """GET VERIFY_URL and return True only on a real HTTP 200.

    Cloudflare Pages needs a few seconds to serve a fresh deployment, so retry
    briefly before declaring failure. Never raises: the status is the result.
    """
    import time, urllib.request, urllib.error
    last = "no attempt made"
    for i in range(attempts):
        try:
            req = urllib.request.Request(
                VERIFY_URL,
                method="GET",
                headers={"User-Agent": "serverbudget-deploy-verify/1.0"},
            )
            with urllib.request.urlopen(req, timeout=20) as r:
                last = f"HTTP {r.status}"
                if r.status == 200:
                    print(f"  Verify: {VERIFY_URL} -> HTTP {r.status} OK")
                    return True
        except urllib.error.HTTPError as e:
            last = f"HTTP {e.code}"
        except Exception as e:  # network/DNS/timeout: report, do not traceback
            last = f"error {type(e).__name__}: {e}"
        if i < attempts - 1:
            time.sleep(delay)
    print(f"  Verify: {VERIFY_URL} -> {last} (NOT 200 after {attempts} attempts)", file=sys.stderr)
    return False


